import type { KeyboardEvent } from 'react';
import {
  ArrowDown,
  ArrowRight,
  Check,
  Circle,
  Code2,
  GitBranch,
  RotateCcw,
  Square,
  Terminal,
} from 'lucide-react';
import { phaseIndex, taskLog } from './model';
import type { DemoAction, DemoTask } from './model';
import { Status } from './DemoPrimitives';

export type Detail = 'Overview' | 'Execution log' | 'Changes';
interface Props {
  selected: DemoTask;
  detail: Detail;
  playing: boolean;
  setDetail: (detail: Detail) => void;
  setPlaying: (playing: boolean) => void;
  replay: () => void;
  act: (action: DemoAction) => void;
}
export function TaskDetail({
  selected,
  detail,
  playing,
  setDetail,
  setPlaying,
  replay,
  act,
}: Props) {
  return (
    <article className="task-detail" aria-label="Selected task">
      <div className="detail-meta">
        <span>
          <span className="mono">{selected.id}</span>
          <span className="dot-separator">/</span>
          {selected.type}
        </span>
        <Status task={selected} />
      </div>
      <h2>{selected.title}</h2>
      <p className="task-description">{selected.description}</p>
      <div className="branch-line">
        <GitBranch size={14} />
        <code>{selected.branch}</code>
        <span>Attempt {selected.attempt}</span>
      </div>
      <div
        className="detail-tabs"
        role="tablist"
        aria-label="Task details"
        onKeyDown={(event) => changeTabWithKeyboard(event, detail, setDetail)}
      >
        {(['Overview', 'Execution log', 'Changes'] as const).map((tab) => (
          <button
            key={tab}
            role="tab"
            id={`tab-${tab.replaceAll(' ', '-')}`}
            aria-controls="detail-panel"
            aria-selected={detail === tab}
            tabIndex={detail === tab ? 0 : -1}
            onClick={() => setDetail(tab)}
          >
            {tab === 'Execution log' && <Terminal size={14} />}
            {tab}
            {tab === 'Changes' && <span>sample</span>}
          </button>
        ))}
      </div>
      <div
        id="detail-panel"
        role="tabpanel"
        aria-labelledby={`tab-${detail.replaceAll(' ', '-')}`}
        className="detail-panel"
      >
        {detail === 'Overview' && <TaskOverview task={selected} />}
        {detail === 'Execution log' && (
          <div className="terminal">
            <div className="terminal-title">
              <Terminal size={13} />
              SIMULATED RUNNER OUTPUT
              <span>attempt {selected.attempt}</span>
            </div>
            <pre aria-live="polite">{taskLog(selected).join('\n')}</pre>
          </div>
        )}
        {detail === 'Changes' && (
          <div className="change-preview">
            <div>
              <Code2 size={15} />
              <strong>Illustrative review artifact</strong>
              <span>sample patch</span>
            </div>
            <p>
              This patch illustrates the review surface; it is not generated by
              an agent. Every task in this demo uses the same example.
            </p>
            <pre>
              <span>
                {'  async function loadActivity(cursor?: string) {\n'}
              </span>
              <span className="diff-removed">
                {"-   return api.get('/activity');\n"}
              </span>
              <span className="diff-added">
                {"+   return api.get('/activity', { cursor, limit: 50 });\n"}
              </span>
              <span>{'  }'}</span>
            </pre>
          </div>
        )}
      </div>
      <div className="task-actions">
        <span aria-live="polite">
          {selected.status === 'FAILED'
            ? 'Worker interrupted. Retry to recover.'
            : selected.status === 'EVALUATING'
              ? 'Review the sample artifact before approving.'
              : selected.status === 'COMPLETED'
                ? 'Task complete. No deployment performed.'
                : playing
                  ? 'Simulation running…'
                  : 'Explore the task lifecycle.'}
        </span>
        <div>
          {playing ? (
            <button
              className="button secondary"
              onClick={() => setPlaying(false)}
            >
              <Square size={13} />
              Pause
            </button>
          ) : (
            <button className="button secondary" onClick={replay}>
              <RotateCcw size={14} />
              Replay
            </button>
          )}
          {selected.status === 'IN_PROGRESS' && (
            <button
              className="button secondary"
              onClick={() => {
                setPlaying(false);
                act('fail');
                setDetail('Execution log');
              }}
            >
              Interrupt worker
            </button>
          )}
          {selected.status === 'FAILED' ? (
            <button
              className="button primary"
              onClick={() => {
                act('retry');
                setPlaying(true);
              }}
            >
              <RotateCcw size={14} />
              Retry task
            </button>
          ) : selected.status === 'EVALUATING' ? (
            <button className="button primary" onClick={() => act('approve')}>
              <Check size={15} />
              Approve sample
            </button>
          ) : (
            ['QUEUED', 'PROVISIONING', 'IN_PROGRESS'].includes(
              selected.status,
            ) && (
              <button
                className="button primary"
                disabled={playing}
                onClick={() => act('advance')}
              >
                Next step
                <ArrowRight size={14} />
              </button>
            )
          )}
        </div>
      </div>
    </article>
  );
}

function TaskOverview({ task }: { task: DemoTask }) {
  const phase = phaseIndex(task.status);
  const phases = [
    ['Accepted', 'Prompt, repository, and task scope recorded.'],
    ['Workspace ready', 'Capacity checked; execution isolated.'],
    ['Agent execution', 'Implementation and tests prepared on a branch.'],
    ['Review boundary', 'Checks and artifacts presented for approval.'],
    ['Task completed', 'Result recorded; release checks remain separate.'],
  ];
  return (
    <div className="timeline">
      {phases.map(([title, description], index) => (
        <div
          key={title}
          className={`timeline-item ${index < phase || task.status === 'COMPLETED' ? 'done' : index === phase ? 'current' : ''}`}
        >
          <span className="timeline-icon">
            {index < phase || task.status === 'COMPLETED' ? (
              <Check size={13} />
            ) : index === phase ? (
              <span className="current-dot" />
            ) : (
              <Circle size={10} />
            )}
          </span>
          <div>
            <strong>
              {task.status === 'FAILED' && index === 2
                ? 'Worker interrupted'
                : title}
            </strong>
            <p>
              {task.status === 'FAILED' && index === 2
                ? 'No further work proceeds until you retry.'
                : description}
            </p>
          </div>
          {index === phase && task.status !== 'COMPLETED' && (
            <span className="phase-tag">
              {task.status === 'FAILED' ? 'STOPPED' : 'CURRENT'}
            </span>
          )}
        </div>
      ))}
      <div className="release-note">
        <ArrowDown size={14} />
        Promotion → deployment → serving verification
      </div>
    </div>
  );
}

function changeTabWithKeyboard(
  event: KeyboardEvent<HTMLDivElement>,
  detail: Detail,
  setDetail: (detail: Detail) => void,
) {
  const tabs: Detail[] = ['Overview', 'Execution log', 'Changes'];
  const index = tabs.indexOf(detail);
  const next =
    event.key === 'ArrowRight'
      ? (index + 1) % tabs.length
      : event.key === 'ArrowLeft'
        ? (index + tabs.length - 1) % tabs.length
        : event.key === 'Home'
          ? 0
          : event.key === 'End'
            ? tabs.length - 1
            : null;
  if (next === null) return;
  event.preventDefault();
  setDetail(tabs[next]);
  const buttons =
    event.currentTarget.querySelectorAll<HTMLButtonElement>('[role="tab"]');
  buttons[next]?.focus();
}
