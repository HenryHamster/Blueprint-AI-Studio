@pytest.fixture(scope="module")
def bash_executable() -> str | None:
    for candidate in (
        Path("C:/Program Files/Git/bin/bash.exe"),
        Path("C:/Program Files/Git/usr/bin/bash.exe"),
    ):
        if candidate.exists():
            return str(candidate)
    return shutil.which("bash")


