@pytest.mark.parametrize("gen", _PARAMS)
class TestGeneratedShellContract:
    """Contract each generated shell script must satisfy.

    Checks are intentionally narrow — they encode real bugs we've shipped
    and want to prevent, not a comprehensive shell-style guide.
    """

    def test_rendering_succeeds(self, gen: ShellGenerator):
        """The generator's .format() / template substitution must succeed
        with the placeholder dict we provide. If this fails, the live
        orchestrator would also fail to render."""
        script = gen.render()
        assert script, f"{gen.name} rendered empty"
        assert script.startswith(gen.expected_shebang), (
            f"{gen.name} missing shebang {gen.expected_shebang!r}"
        )

    def test_bash_syntax(
        self, gen: ShellGenerator, bash_executable: str | None, tmp_path: Path
    ):
        """Structural test: bash -n rejects syntactic nonsense (missing
        `fi`, unbalanced heredoc, bad quoting) without running any code.
        Fast (~10 ms) and catches any regression that breaks parsing.
        """
        if not bash_executable:
            pytest.skip("bash not available on this host")
        path = tmp_path / f"{gen.name}.sh"
        path.write_text(gen.render(), encoding="utf-8")
        result = subprocess.run(
            [bash_executable, "-n", str(path)],
            capture_output=True,
            text=True,
            timeout=10,
        )
        assert result.returncode == 0, f"bash -n rejected {gen.name}:\n{result.stderr}"

    def test_heredoc_terminators_balance(self, gen: ShellGenerator):
        """Every `<<'MARKER'` must be closed by a line consisting solely of
        `MARKER`. A missing terminator silently consumes the rest of the
        script as heredoc input, leading to mysterious runtime failures.
        """
        script = gen.render()
        openers = re.findall(r"<<'([A-Z_][A-Z0-9_]*)'|<<\"([A-Z_][A-Z0-9_]*)\"", script)
        opener_names = {a or b for a, b in openers}
        lines = script.splitlines()
        for name in opener_names:
            closed = any(line.strip() == name for line in lines)
            assert closed, f"{gen.name}: heredoc <<'{name}' has no matching terminator"

    def test_pipefail_pipelines_guarded(self, gen: ShellGenerator):
        """Under `set -euo pipefail`, a pipeline like `grep X | cut -f2-`
        crashes the script when grep finds no match (grep exits 1, pipefail
        propagates, set -e fires ERR).

        Regression: task 0bcfd031 died on
          ``AGENT_TOKEN="$(grep '^X=' /etc/agent.env | cut -d= -f2-)"``
        because that line had no `|| true` guard.

        Check: any command-substitution assignment of the form
        `VAR="$(...  | ... )"` that contains a grep-style read AND isn't
        inside an `if` / `while` test context AND doesn't end with
        `|| true` inside the substitution. We flag only the case we
        actually hit (grep on /etc/agent.env) to avoid false positives.
        """
        script = gen.render()
        offenders = []
        # Find ``VAR="$(... grep ... | ... )"`` on a single logical line.
        pattern = re.compile(
            r'^\s*[A-Z_][A-Z0-9_]*="\$\([^)]*\bgrep\b[^)]*\|[^)]*\)"',
            re.MULTILINE,
        )
        for m in pattern.finditer(script):
            snippet = m.group(0)
            if "|| true" in snippet:
                continue
            # If the substitution is inside a then-branch of `if VAR=...`
            # we'd miss that context; those aren't our bug class anyway.
            line_start = script.rfind("\n", 0, m.start()) + 1
            line_end = script.find("\n", m.end())
            line_no = script.count("\n", 0, m.start()) + 1
            offenders.append((line_no, script[line_start:line_end].strip()))
        assert not offenders, (
            f"{gen.name}: grep|cut pipelines in assignments must end with "
            f"`|| true` inside the command substitution (pipefail + unmatched "
            f"pattern otherwise fires the ERR trap). Offenders:\n"
            + "\n".join(f"  line {i}: {s}" for i, s in offenders)
        )

    def test_inline_poweroff_followed_by_exit_or_scope_close(self, gen: ShellGenerator):
        """``poweroff`` is async — the kernel schedules shutdown but bash
        keeps running until SIGTERM arrives (seconds later). Without a
        terminator (``exit``) or scope-end, subsequent commands execute
        during the shutdown window and produce confusing follow-on
        heartbeats.

        Acceptable successors for a non-terminal ``poweroff``:
          - ``exit N`` in the same scope
          - immediate ``}`` (function body close) or ``)`` (subshell close)
          - the next thing is the terminal ``poweroff`` of the script

        Only flagged: a ``poweroff`` followed by any other substantive
        statement in the same scope.

        Regression: step 6 (systemctl-restart-fail handler) used to call
        ``poweroff`` and then flow into step 6b's success-path heartbeat,
        contradicting the failure heartbeat it had just sent.
        """
        script = gen.render()
        lines = script.splitlines()
        poweroff_lines = [
            i for i, line in enumerate(lines) if line.strip() == "poweroff"
        ]
        if not poweroff_lines:
            return
        non_terminal = poweroff_lines[:-1]
        offenders = []
        for idx in non_terminal:
            # Look at the next substantive line (skip blanks + comments only).
            next_line = None
            for j in range(idx + 1, len(lines)):
                stripped = lines[j].strip()
                if not stripped or stripped.startswith("#"):
                    continue
                next_line = stripped
                break
            if next_line is None:
                continue  # nothing after — fine
            # Acceptable: scope-end (`}`, `)`, or `) &` for a backgrounded
            # subshell), explicit exit, or another poweroff (we're about
            # to terminate anyway).
            if (
                next_line in ("}", ")")
                or next_line.startswith(")")  # e.g. `) &`, `) >log 2>&1`
                or next_line.startswith("exit")
                or next_line == "poweroff"
            ):
                continue
            offenders.append((idx + 1, lines[idx], next_line))
        assert not offenders, (
            f"{gen.name}: inline `poweroff` must be followed by `exit`, "
            f"`}}`, `)`, or another `poweroff` — otherwise bash continues "
            f"running code during the async shutdown window. Offenders:\n"
            + "\n".join(
                f"  line {i}: `{line.strip()}` followed by `{n}`"
                for i, line, n in offenders
            )
        )

    def test_env_file_extracts_strip_quotes(self, gen: ShellGenerator):
        """systemd EnvironmentFile values are written as ``KEY="value"``
        with surrounding double quotes (see materialize_manifest.py).
        A pipeline of ``grep '^KEY=' /etc/agent.env | cut -d= -f2-``
        keeps those quotes — the extracted value is ``"actual"`` not
        ``actual``.

        For HTTP headers like ``X-Agent-Token: "eyJ..."`` the orchestrator's
        JWT verifier rejects the malformed token with 401, ``curl -f``
        exits 22, and (combined with ``set -e`` on the assignment) the
        script silently dies with no ERR trap fire — the exact failure
        mode of task 923f51e8 where every VM hit ~10 min of silent idle
        before the reaper bounced it.

        Fix: pipe through ``tr -d '"'`` (safe for quote-free values like
        JWTs and URLs) before assigning. This test enforces that any
        ``grep`` of /etc/agent.env piped to ``cut`` includes a quote-
        stripping step in the same substitution.
        """
        script = gen.render()
        # Match `VAR="$(... grep ... /etc/agent.env ... | ... cut ... )"`
        # on a single logical line. We only care about the agent.env case
        # because that's the systemd-env-format file with the quoting
        # convention; other files don't follow the convention.
        pattern = re.compile(
            r"^\s*[A-Z_][A-Z0-9_]*=\"\$\("
            r"[^)]*\bgrep\b[^)]*/etc/agent\.env[^)]*"
            r"\|[^)]*\bcut\b[^)]*"
            r"\)\"",
            re.MULTILINE,
        )
        offenders = []
        for m in pattern.finditer(script):
            snippet = m.group(0)
            # Acceptable quote-strip steps inside the substitution.
            if "tr -d '\"'" in snippet or 'tr -d "\\""' in snippet:
                continue
            if re.search(r"sed[^|]*['\"]\^?\\?[\"]", snippet):
                continue
            line_no = script.count("\n", 0, m.start()) + 1
            offenders.append((line_no, snippet[:140]))
        assert not offenders, (
            f"{gen.name}: extracting values from /etc/agent.env via "
            f"`grep | cut` MUST strip the surrounding quotes "
            f"(`| tr -d '\"'`). systemd env file values are written as "
            f'KEY="value"; without stripping the cut output is '
            f'`"value"` (literal quotes) and consumers like the JWT '
            f"verifier reject it. Bash's `var=$(curl -f ...)` simple-"
            f"command rule then exits the script with curl's status "
            f"under set -e, with NO ERR trap fire. Offenders:\n"
            + "\n".join(f"  line {i}: {s}" for i, s in offenders)
        )

    def test_err_trap_captures_diagnostics(self, gen: ShellGenerator):
        """When a VM dies pre-claim with no forensics, BASH_COMMAND is the
        single most useful data point. If an ERR trap exists at all, it
        must capture BASH_COMMAND (not just $LINENO, which bash miscounts
        around heredocs).
        """
        script = gen.render()
        has_err_trap = re.search(r"trap\s+['\"][^'\"]*\bERR\b", script) is not None
        if not has_err_trap:
            return  # no trap is fine for short helpers
        assert "BASH_COMMAND" in script, (
            f"{gen.name}: has an ERR trap but doesn't capture BASH_COMMAND. "
            f"Silent failures will only report $LINENO, which bash miscounts "
            f"around heredocs (see task 4ee24ed6 where line=88 pointed at a "
            f"comment)."
        )

    def test_rendered_has_same_comment_count_as_source(self, gen: ShellGenerator):
        """Regression for the `\\n-in-a-comment` bug (0bcfd031 / 8c9255a9
        post-mortems): if a generator f-string has a comment whose TEXT
        contains ``\\n`` or ``\\\\``, Python's f-string interpolation
        turns the escape into a real newline (or backslash), splitting
        the comment mid-line and often emitting executable bash on the
        second half. Backticks in the stray half open command
        substitutions that fail at runtime with a misleading line
        number.

        bash -n can't catch this because the result IS syntactically
        valid bash — just semantically wrong. shellcheck-at-error
        doesn't flag it either. The only reliable check is on the
        generator source: a comment line in the f-string body should
        render verbatim, and any line-count inflation means something
        got interpolated where it shouldn't.

        Check: every line of the rendered output that starts with
        ``#`` (optionally after whitespace) must contain no unescaped
        characters that f-string would interpret. In practice we detect
        the bug symptom: a rendered line that LOOKS like executable
        bash but came from the second half of a split comment.

        We flag: rendered lines that start with leading whitespace +
        backtick, which is the signature of a comment gone wrong.
        """
        script = gen.render()
        offenders = []
        for i, line in enumerate(script.splitlines(), 1):
            stripped = line.lstrip()
            # Real bash rarely starts a LINE with a backtick (command
            # substitution at line-start). Split-comment fragments do.
            if stripped.startswith("`"):
                offenders.append((i, line))
        assert not offenders, (
            f"{gen.name}: lines starting with a backtick are almost "
            f"certainly split-comment fragments from f-string "
            f"interpolation turning `\\n` in a source comment into a "
            f"real newline (see task 8c9255a9 post-mortem). Remove "
            f"backslash escapes and backticks from comments inside the "
            f"generator f-string body.\n"
            + "\n".join(f"  line {i}: {line!r}" for i, line in offenders)
        )

    def test_no_multi_line_embedded_non_bash_code(self, gen: ShellGenerator):
        """Regression: the single worst class of bug we shipped (task
        0bcfd031 / c94d6d9b post-mortem) came from embedding a multi-line
        Python heredoc inside a bash heredoc inside a Python f-string.
        Three levels of escape interpretation, silently mis-nested, broke
        every VM with a SyntaxError we never saw because the ERR path
        also got corrupted in the same pass.

        Rule: generated bash may contain SHORT (one-line) ``python3 -c``,
        ``node -e``, ``jq`` etc., but NOT multi-line heredocs of another
        language. Embed such scripts as real .py/.js files loaded via
        base64 (see _agent_scripts/materialize_manifest.py for the
        pattern).

        We flag any ``<<'MARKER'`` heredoc whose body is identified as
        Python, JS, or Ruby (by imports / require / similar).
        """
        script = gen.render()
        # Find every heredoc: ``<<'MARKER'`` through a line starting with
        # MARKER (optionally indented). Body is everything between.
        heredoc_pat = re.compile(
            r"<<'([A-Z_][A-Z0-9_]*)'\s*\n(.*?)\n\s*\1\s*$",
            re.MULTILINE | re.DOTALL,
        )
        offenders = []
        for m in heredoc_pat.finditer(script):
            marker = m.group(1)
            body = m.group(2)
            # Skip trivial heredocs (JSON, short bash, etc.)
            if body.count("\n") < 2:
                continue
            # Language fingerprints — these are cheap and specific
            is_python = any(
                token in body
                for token in (
                    "\nimport ",
                    "\nfrom ",
                    "def ",
                    "print(",
                    "sys.argv",
                    "__name__",
                )
            )
            is_node = any(token in body for token in ("require(", "console.log", "=>"))
            lang = "python" if is_python else "node" if is_node else None
            if lang:
                offenders.append((marker, lang, body[:80]))
        assert not offenders, (
            f"{gen.name}: detected multi-line embedded {', '.join(lang for _, lang, _ in offenders)} "
            f"heredocs in generated bash. Escape semantics across 3 layers "
            f"(generator→bash→embedded-lang) are a landmine that has bitten "
            f"us in production (see 0bcfd031 / c94d6d9b post-mortems).\n"
            f"Fix: move the embedded code to a real .py/.js file under a "
            f"scripts dir and load it via base64 (see "
            f"backend/app/_agent_scripts/materialize_manifest.py). Offenders:\n"
            + "\n".join(
                f"  <<'{m}' ({lang}): {preview!r}..." for m, lang, preview in offenders
            )
        )


