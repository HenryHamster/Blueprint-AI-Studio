"""
Static checks on bash scripts generated by the orchestrator.

The orchestrator emits bash scripts into GCE instance metadata (and agent
helper scripts to VM disks). A typo, an inverted `if`, or an unguarded
pipeline in any of those scripts breaks silently — the VM boots, the
script dies, the reaper eventually kills the VM with no forensics.

This module:
  1. Renders each generator with placeholder values.
  2. Runs `bash -n` to catch syntax errors.
  3. Applies a small set of pattern checks for the bug classes we've
     actually hit in production (see bug_classes below).

New generators added to the orchestrator get protection by appending a
single line to :data:`GENERATORS`. The cost of running the suite is
dominated by `bash -n` invocations — a few tens of milliseconds each.

Related bug history (see comments on each check for details):
  - task 595c235d, 548043b9: unbounded payload + silent startup death
  - task 4ee24ed6: `set +e` did not suppress the ERR trap
  - task 0bcfd031: inverted `if ! python3 ...` branches; unguarded
    `grep | cut` pipeline crashed on pipefail + no match
"""
from __future__ import annotations

import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import pytest

from app import compute
from app.compute_startup_script import build_agent_startup_script


