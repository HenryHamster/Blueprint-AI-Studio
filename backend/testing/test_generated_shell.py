# ---------------------------------------------------------------------------
# shellcheck — runs if the binary is available. Complements the narrow
# pattern checks above with generic shell-hygiene warnings.
# ---------------------------------------------------------------------------
# Why -S error (not warning/info):
#   - generated scripts have lots of intentional "warnings" that aren't
#     bugs (e.g. SC2154 "var referenced but not assigned" for $LINENO in
#     a single-quoted trap — it's assigned by bash, not our code)
#   - -S error gates on actually-wrong usage: wrong flag to command,
#     bad redirection, unbalanced quoting that bash -n missed
#   - tighten over time by lowering severity and adding focused excludes

# Noisy codes we've validated as false positives in our generators:
_SHELLCHECK_EXCLUDES = [
    # SC1091: "Not following: ... was not specified as input"  — we source
    # /etc/agent.env which doesn't exist in the render environment
    "SC1091",
    # SC2154: "var referenced but not assigned"  — $BASH_COMMAND, $LINENO
    # inside single-quoted trap strings are assigned by bash itself
    "SC2154",
    # SC2157: "Argument to -n is always true due to literal strings."  —
    # `if [ -n "{placeholder}" ]` is the canonical pattern for optional-
    # argument templating; in production the literal IS variable (empty
    # or not). The test renderer substitutes a concrete value, which
    # makes shellcheck think it's unconditional.
    "SC2157",
]


@pytest.fixture(scope="module")
def shellcheck_available() -> bool:
    return shutil.which("shellcheck") is not None


@pytest.mark.parametrize("gen", _PARAMS)
def test_shellcheck_no_errors(
    gen: ShellGenerator, shellcheck_available: bool, tmp_path: Path
):
    """Run shellcheck at severity=error. Skipped if shellcheck isn't
    installed — add it via `apt-get install shellcheck` in the test image
    to gate CI on this."""
    if not shellcheck_available:
        pytest.skip("shellcheck not installed (install in test image to enable)")
    path = tmp_path / f"{gen.name}.sh"
    path.write_text(gen.render(), encoding="utf-8")
    cmd = [
        "shellcheck",
        # Per-generator dialect, NOT a blanket constant: this flag overrides
        # shebang sniffing, so hardcoding bash would silently check a future
        # `#!/bin/sh` generator under bash rules. See ShellGenerator.shell.
        f"--shell={gen.shell}",
        "-S",
        "error",
        f"--exclude={','.join(_SHELLCHECK_EXCLUDES)}",
        str(path),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=15)
    assert result.returncode == 0, (
        f"shellcheck errors in {gen.name}:\n{result.stdout}\n{result.stderr}"
    )


@pytest.mark.parametrize("gen", _PARAMS)
def test_shellcheck_shell_matches_shebang(gen: ShellGenerator):
    """The declared shellcheck dialect must agree with the emitted shebang.

    `--shell=` overrides sniffing. This is the guard that keeps the override from
    lying: a generator that starts emitting `#!/bin/sh` while still declaring
    `shell="bash"` gets checked under the wrong dialect and its bashisms sail
    through. Generators with no shebang (the `bash -lc` wrappers) are exempt —
    there is nothing to disagree with.
    """
    if not gen.expected_shebang:
        return
    # Handles both `#!/bin/bash` and `#!/usr/bin/env bash`.
    interpreter = gen.expected_shebang.split()[-1].rsplit("/", 1)[-1]
    assert interpreter == gen.shell, (
        f"{gen.name} emits {gen.expected_shebang!r} but is shellcheck'd as "
        f"--shell={gen.shell}; the override would hide dialect errors"
    )


