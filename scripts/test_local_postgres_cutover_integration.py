#!/usr/bin/env python3
"""Opt-in Linux/Docker integration test for the PostgreSQL cutover path.

Run explicitly on a Linux Docker host:

    BLUEPRINT_RUN_POSTGRES_CUTOVER_INTEGRATION=1 \
      python3 scripts/test_local_postgres_cutover_integration.py -v

The test is skipped by default. When enabled, it creates two temporary
PostgreSQL 15 containers, exercises the real ``dump-source`` and
``verify-import`` commands, and always removes only those named containers.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
import unittest
import uuid
from pathlib import Path
from typing import Sequence


RUN_INTEGRATION = os.environ.get("BLUEPRINT_RUN_POSTGRES_CUTOVER_INTEGRATION") == "1"
POSTGRES_IMAGE = os.environ.get("BLUEPRINT_POSTGRES_TEST_IMAGE", "postgres:15")
SCRIPT = Path(__file__).with_name("local_postgres_cutover.py").resolve()

SOURCE_SCHEMA = r"""
CREATE TYPE public.work_state AS ENUM ('queued', 'running', 'done');
CREATE TYPE public.artifact_kind AS ENUM ('log', 'report');

CREATE TABLE public.alembic_version (
    version_num varchar(32) PRIMARY KEY
);
INSERT INTO public.alembic_version(version_num) VALUES ('integration_001');

CREATE TABLE public.alloweduser (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE
);

CREATE TABLE public.project (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    status public.work_state NOT NULL
);

CREATE TABLE public.task (
    id bigserial PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.project(id),
    parent_task_id bigint REFERENCES public.task(id),
    status public.work_state NOT NULL,
    description text NOT NULL
);

CREATE TABLE public.artifact (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES public.task(id),
    artifact_type public.artifact_kind NOT NULL,
    payload jsonb NOT NULL
);

CREATE TABLE public.task_audit (
    id bigserial PRIMARY KEY,
    task_id bigint NOT NULL,
    observed_status public.work_state NOT NULL,
    note text NOT NULL
);

CREATE FUNCTION public.record_task_insert() RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    INSERT INTO public.task_audit(task_id, observed_status, note)
    VALUES (NEW.id, NEW.status, 'created by trigger');
    RETURN NEW;
END
$function$;

CREATE TRIGGER task_insert_audit
AFTER INSERT ON public.task
FOR EACH ROW EXECUTE FUNCTION public.record_task_insert();

CREATE VIEW public.task_summary AS
SELECT t.id, p.name AS project_name, t.status, t.description
FROM public.task AS t
JOIN public.project AS p ON p.id = t.project_id;

INSERT INTO public.alloweduser(email)
VALUES ('owner@example.test'), ('runner@example.test');
INSERT INTO public.project(name, status)
VALUES ('integration project', 'running');
INSERT INTO public.task(project_id, status, description)
VALUES (1, 'queued', 'first task');
INSERT INTO public.task(project_id, parent_task_id, status, description)
VALUES (1, 1, 'done', 'child task');
INSERT INTO public.artifact(task_id, artifact_type, payload)
VALUES (2, 'report', '{"verified": true, "rows": 2}');
SELECT setval(
    pg_get_serial_sequence('public.task', 'id'),
    (SELECT max(id) + 7 FROM public.task),
    true
);
"""

PARITY_SQL = r"""
SELECT jsonb_build_object(
    'allowed_users', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (SELECT id, email FROM public.alloweduser) AS q
    ),
    'projects', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (SELECT id, name, status::text AS status FROM public.project) AS q
    ),
    'tasks', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (
            SELECT id, project_id, parent_task_id, status::text AS status, description
            FROM public.task
        ) AS q
    ),
    'artifacts', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (
            SELECT id, task_id, artifact_type::text AS artifact_type, payload
            FROM public.artifact
        ) AS q
    ),
    'audit', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (
            SELECT id, task_id, observed_status::text AS observed_status, note
            FROM public.task_audit
        ) AS q
    ),
    'view_rows', (
        SELECT jsonb_agg(to_jsonb(q) ORDER BY q.id)
        FROM (
            SELECT id, project_name, status::text AS status, description
            FROM public.task_summary
        ) AS q
    ),
    'enum_labels', (
        SELECT jsonb_agg(e.enumlabel ORDER BY e.enumsortorder)
        FROM pg_enum AS e
        JOIN pg_type AS t ON t.oid = e.enumtypid
        JOIN pg_namespace AS n ON n.oid = t.typnamespace
        WHERE n.nspname = 'public' AND t.typname = 'work_state'
    ),
    'function_language', (
        SELECT l.lanname
        FROM pg_proc AS p
        JOIN pg_namespace AS n ON n.oid = p.pronamespace
        JOIN pg_language AS l ON l.oid = p.prolang
        WHERE n.nspname = 'public' AND p.proname = 'record_task_insert'
    ),
    'trigger_names', (
        SELECT jsonb_agg(t.tgname ORDER BY t.tgname)
        FROM pg_trigger AS t
        JOIN pg_class AS c ON c.oid = t.tgrelid
        JOIN pg_namespace AS n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND NOT t.tgisinternal
    ),
    'task_sequence', (
        SELECT jsonb_build_object('last_value', last_value, 'is_called', is_called)
        FROM public.task_id_seq
    )
)::text;
"""


def _iso(moment: dt.datetime) -> str:
    return moment.astimezone(dt.timezone.utc).isoformat().replace("+00:00", "Z")


@unittest.skipUnless(
    RUN_INTEGRATION and sys.platform.startswith("linux"),
    "set BLUEPRINT_RUN_POSTGRES_CUTOVER_INTEGRATION=1 on a Linux Docker host",
)
class PostgresCutoverIntegrationTests(unittest.TestCase):
    source_container: str
    target_container: str

    @classmethod
    def setUpClass(cls) -> None:
        if shutil.which("docker") is None:
            raise unittest.SkipTest("docker CLI is unavailable")
        daemon = subprocess.run(
            ["docker", "info"],
            capture_output=True,
            text=True,
            # Below MAX_INNER_OPERATION_SECONDS (backend/testing/
            # test_harness_timeout_budgets.py) so this probe can report its own
            # failure rather than being killed by the harness first.
            timeout=20,
            check=False,
        )
        if daemon.returncode != 0:
            raise unittest.SkipTest(f"Docker daemon is unavailable: {daemon.stderr.strip()}")

        suffix = uuid.uuid4().hex[:12]
        cls.source_container = f"blueprint-cutover-source-{suffix}"
        cls.target_container = f"blueprint-cutover-target-{suffix}"
        cls._containers: list[str] = []
        cls._secret_directory = tempfile.TemporaryDirectory(
            prefix="blueprint-cutover-secrets-"
        )
        secret_root = Path(cls._secret_directory.name)
        password = secrets.token_urlsafe(24)
        cls.password_file = secret_root / "postgres-password"
        cls.password_file.write_text(password, encoding="utf-8")
        os.chmod(cls.password_file, 0o600)
        docker_env = secret_root / "postgres.env"
        docker_env.write_text(f"POSTGRES_PASSWORD={password}\n", encoding="utf-8")
        os.chmod(docker_env, 0o600)
        try:
            for name in (cls.source_container, cls.target_container):
                cls._run(
                    [
                        "docker",
                        "run",
                        "--detach",
                        "--name",
                        name,
                        "--env-file",
                        str(docker_env),
                        "--env",
                        "POSTGRES_USER=blueprint",
                        "--env",
                        "POSTGRES_DB=blueprint",
                        POSTGRES_IMAGE,
                    ],
                    timeout=180,
                )
                cls._containers.append(name)
                cls._wait_ready(name)
        except Exception:
            cls._cleanup_containers()
            cls._secret_directory.cleanup()
            raise

    @classmethod
    def tearDownClass(cls) -> None:
        cls._cleanup_containers()
        cls._secret_directory.cleanup()

    @classmethod
    def _cleanup_containers(cls) -> None:
        for container in reversed(getattr(cls, "_containers", [])):
            subprocess.run(
                ["docker", "rm", "--force", container],
                capture_output=True,
                # Below MAX_INNER_OPERATION_SECONDS (backend/testing/
                # test_harness_timeout_budgets.py). A helper cannot carry a
                # pytest-timeout marker on behalf of its callers, so its own
                # budget has to stay under that ceiling unconditionally.
                timeout=20,
                check=False,
            )
        cls._containers = []

    @staticmethod
    def _run(
        argv: Sequence[str],
        *,
        input_text: str | None = None,
        timeout: int = 120,
    ) -> subprocess.CompletedProcess[str]:
        result = subprocess.run(
            list(argv),
            input=input_text,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        if result.returncode != 0:
            raise AssertionError(
                f"command failed ({result.returncode}): {list(argv)!r}\n"
                f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
            )
        return result

    @classmethod
    def _wait_ready(cls, container: str) -> None:
        deadline = time.monotonic() + 30
        while time.monotonic() < deadline:
            result = subprocess.run(
                [
                    "docker",
                    "exec",
                    container,
                    "pg_isready",
                    "--username",
                    "blueprint",
                    "--dbname",
                    "blueprint",
                ],
                capture_output=True,
                text=True,
                timeout=5,
                check=False,
            )
            if result.returncode == 0:
                return
            time.sleep(0.25)
        raise AssertionError(f"PostgreSQL did not become ready in {container}")

    @classmethod
    def _psql(cls, container: str, sql: str) -> str:
        return cls._run(
            [
                "docker",
                "exec",
                "--interactive",
                container,
                "psql",
                "--no-psqlrc",
                "--quiet",
                "--set",
                "ON_ERROR_STOP=1",
                "--tuples-only",
                "--no-align",
                "--username",
                "blueprint",
                "--dbname",
                "blueprint",
            ],
            input_text=sql,
        ).stdout.strip()

    def test_custom_dump_restore_and_snapshot_parity(self) -> None:
        self._psql(self.source_container, SOURCE_SCHEMA)

        with tempfile.TemporaryDirectory(prefix="blueprint-cutover-integration-") as directory:
            root = Path(directory)
            fence_path = root / "source-fence.json"
            artifact_path = root / "source.dump"
            source_snapshot_path = root / "source-snapshot.json"
            manifest_path = root / "dump-manifest.json"
            target_snapshot_path = root / "target-snapshot.json"
            result_path = root / "result.json"

            now = dt.datetime.now(dt.timezone.utc)
            source_identity = {
                "project_id": "integration-test",
                "instance": "cutover-integration-source",
                "database": "blueprint",
                "cloud_run_service": "cutover-integration-api",
                "cloud_run_region": "integration-region",
            }

            def bound_raw(name: str, kind: str, value: object) -> dict[str, object]:
                path = root / name
                raw = (json.dumps(value, sort_keys=True) + "\n").encode()
                path.write_bytes(raw)
                os.chmod(path, 0o600)
                return {
                    "kind": kind,
                    "path": str(path),
                    "sha256": hashlib.sha256(raw).hexdigest(),
                }

            raw_evidence = [
                bound_raw(
                    "cloud-run-fence.json",
                    "cloud_run_fence",
                    {
                        "schema_version": 1,
                        "kind": "cloud-run-write-fence",
                        "request": {
                            "project_id": source_identity["project_id"],
                            "region": source_identity["cloud_run_region"],
                            "service": source_identity["cloud_run_service"],
                        },
                        "project": {
                            "projectId": source_identity["project_id"],
                            "projectNumber": "123456789",
                        },
                        "service": {
                            "metadata": {
                                "name": source_identity["cloud_run_service"],
                                "namespace": "123456789",
                                "labels": {
                                    "cloud.googleapis.com/location": source_identity[
                                        "cloud_run_region"
                                    ]
                                },
                            }
                        },
                        "policy": {"bindings": []},
                    },
                ),
                bound_raw(
                    "cloud-sql-instance.json",
                    "cloud_sql_instance",
                    {
                        "name": source_identity["instance"],
                        "databaseVersion": "POSTGRES_15",
                        "region": "integration-region",
                        "connectionName": (
                            f"{source_identity['project_id']}:integration-region:"
                            f"{source_identity['instance']}"
                        ),
                    },
                ),
                bound_raw(
                    "password-rotation.json",
                    "password_rotation_operation",
                    {
                        "status": "DONE",
                        "operationType": "UPDATE_USER",
                        "targetId": source_identity["instance"],
                        "targetProject": source_identity["project_id"],
                        "error": None,
                    },
                ),
            ]
            session_observations = []
            for index, seconds_ago in enumerate((40, 25, 10), start=1):
                observation = bound_raw(
                    f"sessions-{index}.json",
                    f"session_observation_{index}",
                    [],
                )
                observation.update(
                    {
                        "captured_at": _iso(now - dt.timedelta(seconds=seconds_ago)),
                        "old_session_count": 0,
                    }
                )
                session_observations.append(observation)

            fence = {
                "schema_version": 1,
                "kind": "postgres-durable-source-fence",
                "source": source_identity,
                "password_rotated": True,
                "old_sessions_terminated": True,
                "raw_evidence": raw_evidence,
                "session_observations": session_observations,
                "freeze_started_at": _iso(now - dt.timedelta(seconds=4)),
                "fence_verified_at": _iso(now - dt.timedelta(seconds=1)),
            }
            fence_path.write_text(json.dumps(fence), encoding="utf-8")
            os.chmod(fence_path, 0o600)

            self._run(
                [
                    sys.executable,
                    str(SCRIPT),
                    "dump-source",
                    "--source-fence",
                    str(fence_path),
                    "--container",
                    self.source_container,
                    "--host",
                    "127.0.0.1",
                    "--port",
                    "5432",
                    "--database",
                    "blueprint",
                    "--user",
                    "blueprint",
                    "--password-file",
                    str(self.password_file),
                    "--instance",
                    source_identity["instance"],
                    "--artifact-output",
                    str(artifact_path),
                    "--source-snapshot-output",
                    str(source_snapshot_path),
                    "--manifest-output",
                    str(manifest_path),
                    "--timeout-seconds",
                    "300",
                ],
                timeout=360,
            )

            self.assertEqual(artifact_path.read_bytes()[:5], b"PGDMP")
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            self.assertEqual(manifest["kind"], "postgres-direct-dump-manifest")
            self.assertEqual(manifest["pg_dump"]["format"], "custom")
            self.assertEqual(
                manifest["artifact"]["sha256"],
                hashlib.sha256(artifact_path.read_bytes()).hexdigest(),
            )

            self._run(
                [
                    sys.executable,
                    str(SCRIPT),
                    "verify-import",
                    "--source-snapshot",
                    str(source_snapshot_path),
                    "--source-fence",
                    str(fence_path),
                    "--export-manifest",
                    str(manifest_path),
                    "--target-container",
                    self.target_container,
                    "--target-database",
                    "blueprint",
                    "--target-user",
                    "blueprint",
                    "--source-owner",
                    "blueprint",
                    "--target-instance",
                    "cutover-integration-target",
                    "--target-snapshot-output",
                    str(target_snapshot_path),
                    "--result-output",
                    str(result_path),
                    "--import-timeout-seconds",
                    "300",
                ],
                timeout=360,
            )

            result = json.loads(result_path.read_text(encoding="utf-8"))
            self.assertEqual(result["outcome"], "success")
            source_snapshot = json.loads(source_snapshot_path.read_text(encoding="utf-8"))
            target_snapshot = json.loads(target_snapshot_path.read_text(encoding="utf-8"))
            for field in result["comparison_fields"]:
                self.assertEqual(
                    source_snapshot[field],
                    target_snapshot[field],
                    f"snapshot mismatch for {field}",
                )

            source_state = json.loads(self._psql(self.source_container, PARITY_SQL))
            target_state = json.loads(self._psql(self.target_container, PARITY_SQL))
            self.assertEqual(source_state, target_state)
            self.assertEqual(source_state["enum_labels"], ["queued", "running", "done"])
            self.assertEqual(source_state["function_language"], "plpgsql")
            self.assertIn("task_insert_audit", source_state["trigger_names"])
            self.assertEqual(len(source_state["view_rows"]), 2)
            self.assertEqual(len(source_state["audit"]), 2)
            self.assertEqual(source_state["task_sequence"]["last_value"], 9)


if __name__ == "__main__":
    unittest.main()
