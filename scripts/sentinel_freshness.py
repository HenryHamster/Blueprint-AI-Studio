#!/usr/bin/env python3
"""Always-on derived-artifact freshness lane for the ``./check`` publication gate.

WHY THIS LANE EXISTS
--------------------
This repository stores several DERIVED artifacts as hand-maintained checked-in
files -- the websocket emitter inventory fixture, the hand-kept
``WEBSOCKET_EMITTER_INVENTORY`` dict, the conversational-Workday manifest's
per-file test counts, the ranked-queue and durations artifacts, the module-size
cap ledger.  Each has a drift sentinel that regenerates the artifact's expected
value from source and compares.

Before this lane, the publication gate's ALWAYS-ON portion covered exactly ONE
of them: the module-size cap ledger, and only because its guard happens to be a
standalone checker (``backend/testing/check_size_limits.py``) rather than a
pytest node.  Every other derived artifact's guard is a pytest drift sentinel
that runs only under ``./check test``.  That asymmetry is arbitrary -- the size
ledger is not more load-bearing than the emitter inventory -- and it is the
whole reason promotion PR #17764 (and #17738 before it) fail-closed on backend
shards whose only content was stale checked-in guard data.

Stale guard data has a second property that makes late detection expensive: it
is self-concealing.  The static release guard attributes failures differentially
(a failure present in BOTH the task tree and the base tree is INHERITED and
warn-passes), so the drift is visible on exactly one pull request -- the one
that introduces it.  Every later PR inherits it and passes.  The next tree with
no base to attribute against is the automain->main promotion matrix, which is
where the cost lands.

WHAT IT DOES
------------
Runs exactly the drift sentinels that
``backend/testing/drift_sentinel_surfaces.json`` registers for the surfaces THIS
diff touches -- never the whole standalone corpus -- through the harness's own
selector channel, and attributes them against the extracted base tree:

* a sentinel failing in the task tree but not the base tree BLOCKS, naming the
  sentinel and the exact regeneration command;
* a sentinel failing in BOTH trees does not block (inherited drift must never
  stop the fleet) but is reported loudly as stale guard data ON THE BASE BRANCH,
  again with the exact regeneration command, because that is the state that
  fail-closes the next promotion PR;
* an unusable current or baseline result fails CLOSED -- a lane that cannot tell
  must never report clean.

SELF-REPAIR (``--fix``)
-----------------------
Detection was never the gap.  The gap is that nothing ever RAN the command this
lane prints: three hand-written repair commits landed on the integration branch
in three days (``e38d74d4e1``, ``084cda2dd7``, ``7e8069cde0``), each cut after a
promotion PR had already gone red, and the inherited-drift branch above means
drift that reaches the base branch is repaired by nobody until the promotion
matrix fail-closes on it.

Under ``--fix`` the lane re-runs the generator for a drifted sentinel whose
artifact is registered in ``derived_artifact_repair.AUTOREPAIRABLE``, then
RE-RUNS that sentinel to confirm the drift actually cleared.  ``./pr open``
stages the working tree with ``git add -A``, so the regenerated bytes ride out
on the same PR and the drift never reaches the integration branch.  Inherited
drift is healed the same way, which is what makes the fix structural instead of
one more reminder.

This is not a guard regenerating its own evidence.  The allowlist admits ONLY
artifacts that encode no decision -- a pure report with no consumer but its own
guard.  Every ratchet, floor, snapshot, cap and measurement in the repo is
excluded by name in ``derived_artifact_repair.NEVER_AUTOREPAIR`` and keeps the
report-only behaviour; so does every sentinel when ``--fix`` is not passed.  A
repair that does not clear the drift still blocks, and a generator that fails
to run fails the lane rather than being reported as a repair.

``--fix`` also runs the ROT-ONLY repairs in
``derived_artifact_repair.ROT_ONLY_AUTOREPAIR``.  Those sentinels stay in
``NEVER_AUTOREPAIR`` -- their artifacts are measurements and may never be
regenerated -- but a measurement fails in two directions and only one of them
needs a measurement to fix.  A row naming a test that no longer exists is
deleted for free from the tree; a test with no row still blocks and still costs
a timed run.  The registered command can only DELETE, so the unpayable half is
structurally out of its reach.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

try:  # absent from synthetic fixtures that copy scripts/ piecemeal
    from utf8_io import force_utf8_streams  # noqa: E402
except ImportError:  # pragma: no cover - fixture trees run on UTF-8 hosts
    def force_utf8_streams() -> None:
        return None

from derived_artifact_repair import (  # noqa: E402
    AUTOREPAIRABLE,
    MEASUREMENT_TAX_GUIDANCE,
    ROT_ONLY_AUTOREPAIR,
    RepairOutcome,
    repair_entry,
    repair_sentinels,
)
from static_release_guard import (  # noqa: E402
    SENTINEL_REPAIR_COMMANDS,
    JUnitReport,
    _base_ref,
    _changed_files,
    _extract_base,
    _harness_selector,
    _pytest_result_is_authoritative,
    _run_static_corpus,
    classify_verification,
    parse_junit_report,
    sentinel_file,
    surface_sentinels,
)

PREFIX = "[sentinel freshness]"


def select_sentinels(changed: list[str], repo_root: str) -> list[str]:
    """Registered drift sentinels whose surface globs this diff matches.

    Selection is delegated to the SAME accessor the merge-time impacted-test
    gate and ``static_release_guard._is_static_scope`` use, so this lane cannot
    drift out of sync with the registry it enforces.
    """
    return sorted(surface_sentinels(changed, repo_root))


def repair_hint(sentinel: str) -> str:
    """The registered regeneration command for ``sentinel``, or a fallback."""
    command = SENTINEL_REPAIR_COMMANDS.get(sentinel_file(sentinel))
    if command:
        return command
    return (
        "no regeneration command is registered in "
        "static_release_guard.SENTINEL_REPAIR_COMMANDS for this sentinel; add "
        "one so the next failure names its own repair"
    )


def _report_sentinels(label: str, sentinels: list[str], stream) -> None:
    for sentinel in sentinels:
        print(f"{PREFIX} {label}: {sentinel}", file=stream)
        print(f"{PREFIX}   repair: {repair_hint(sentinel)}", file=stream)
        note = MEASUREMENT_TAX_GUIDANCE.get(sentinel_file(sentinel))
        if note:
            # A measurement artifact cannot be repaired from a checkout, so the
            # bare repair command reads as "run this" when the honest answer is
            # "you cannot, and here is what NOT to do instead". Both shortcuts
            # this warns off were observed in the wild.
            print(f"{PREFIX}   note: {note}", file=stream)


def _failing_sentinels(failures: dict[str, str], sentinels: list[str]) -> list[str]:
    """Sentinels named by a JUnit failure map, matched on the file's basename.

    JUnit route keys carry the harness-relative path (``testing/test_x.py``)
    while the registry names them repo-relative, so the comparison is on the
    file's basename, which is unique across the standalone roster.
    """
    blob = " ".join([*failures.keys(), *(str(value) for value in failures.values())])
    return [
        sentinel
        for sentinel in sentinels
        if sentinel_file(sentinel).rsplit("/", 1)[-1] in blob
    ]


def _routes_naming(failures: dict[str, str], sentinels: list[str]) -> list[str]:
    """The individual failure routes attributable to ``sentinels``.

    ``_failing_sentinels`` answers the inverse question over a single blob,
    which is precise enough to NAME an offender but not to REMOVE one: dropping
    a healed sentinel's failures must never drop a different sentinel's.
    """
    names = {sentinel_file(sentinel).rsplit("/", 1)[-1] for sentinel in sentinels}
    return [
        route
        for route, message in failures.items()
        if any(name in f"{route} {message}" for name in names)
    ]


def _report_repair(outcome: RepairOutcome, stream) -> None:
    for sentinel in outcome.repaired:
        rot_only = sentinel in ROT_ONLY_AUTOREPAIR
        label = "SELF-HEALED (rot only)" if rot_only else "SELF-HEALED"
        print(f"{PREFIX} {label}: {sentinel}", file=stream)
        for artifact in repair_entry(sentinel).artifacts:
            verb = "pruned stale entries from" if rot_only else "regenerated"
            print(
                f"{PREFIX}   {verb} {artifact} — `./pr open` stages it with "
                "`git add -A`; on a developer host commit it yourself",
                file=stream,
            )
    for sentinel in outcome.already_fresh:
        if sentinel in ROT_ONLY_AUTOREPAIR:
            # The pruner found nothing to delete, so whatever is failing is NOT
            # rot. For a measurement artifact that almost always means the
            # opposite direction — a test with no timing — and saying "real
            # defect" there would send the reader looking for a bug that is not
            # any bug at all.
            print(
                f"{PREFIX} ADDITION, NOT ROT: {sentinel} has no stale entries to "
                "prune, so its failure is a MISSING measurement, not phantom "
                "data. Run `python scripts/derived_artifact_classify.py "
                "--explain-unclassified` for the exact entries and the cost of "
                "the repair; there is no offline shortcut and fabricating a row "
                "is worse than the red",
                file=stream,
            )
            continue
        # The generator produced identical bytes, so this sentinel's failure is
        # NOT staleness of its artifact. Say so instead of implying a repair.
        print(
            f"{PREFIX} NOT STALENESS: {sentinel} still fails after its generator "
            "reproduced the checked-in bytes exactly — the guard is reporting a "
            "real defect, not drift",
            file=stream,
        )


def _self_repair(
    repo: Path,
    tmp: str,
    sentinels: list[str],
    current_report: JUnitReport,
) -> int | None:
    """Regenerate what may be regenerated, then re-run to prove it cleared.

    Returns an exit code when the lane must stop here, or ``None`` to continue
    into ordinary attribution with ``current_report.failures`` updated in place.
    """
    drifted = _failing_sentinels(current_report.failures, sentinels)
    candidates = [sentinel for sentinel in drifted if sentinel in AUTOREPAIRABLE]
    rot_only = [sentinel for sentinel in drifted if sentinel in ROT_ONLY_AUTOREPAIR]
    if not candidates and not rot_only:
        return None

    # Two passes over DISJOINT registries, never one pass over their union: the
    # registry argument narrows what a pass may execute, so a sentinel can only
    # ever be run by the registry that classified it. An empty pass is skipped
    # rather than run with an empty selection, so the call log records only
    # repairs that were actually attempted.
    outcome = RepairOutcome()
    if candidates:
        outcome = outcome.merge(repair_sentinels(repo, candidates))
    if rot_only:
        outcome = outcome.merge(
            repair_sentinels(repo, rot_only, registry=ROT_ONLY_AUTOREPAIR)
        )
    if outcome.failed:
        print(
            f"{PREFIX} ERROR: a registered generator could not be run; refusing "
            f"to report clean: {json.dumps(outcome.failed, sort_keys=True)}",
            file=sys.stderr,
        )
        return 1
    if not outcome.ran:  # pragma: no cover - candidates are all registered
        return None

    _report_repair(outcome, sys.stderr)

    # Never take the repair's word for it. Re-run exactly the repaired
    # sentinels: if the artifact is genuinely fresh they pass, and if the
    # failure was something else entirely it survives and still blocks.
    rerun_selectors = [_harness_selector(sentinel) for sentinel in outcome.ran]
    rerun_junit = Path(tmp) / "repaired.xml"
    rerun_result = _run_static_corpus(repo, rerun_junit, selectors=rerun_selectors)
    try:
        rerun_report = parse_junit_report(
            rerun_junit, tree_root=repo, label="current"
        )
    except RuntimeError as exc:
        print(
            f"{PREFIX} ERROR: cannot read the post-repair sentinel run: {exc}",
            file=sys.stderr,
        )
        return 1
    if not _pytest_result_is_authoritative(
        rerun_result, rerun_report, authority="sentinel_repair_unusable"
    ):
        print(
            f"{PREFIX} ERROR: the post-repair sentinel run is not attributable; "
            "refusing to credit a repair it cannot confirm",
            file=sys.stderr,
        )
        return 1

    for route in _routes_naming(current_report.failures, list(outcome.ran)):
        current_report.failures.pop(route, None)
    current_report.failures.update(rerun_report.failures)

    if not current_report.failures:
        print(
            f"{PREFIX} PASS - derived guard data was stale and has been "
            f"regenerated: {json.dumps(list(outcome.changed_artifacts()))}"
        )
        return 0
    return None


def _base_selectors(selectors: list[str], base_root: Path) -> list[str]:
    """Selectors whose underlying file exists in the extracted base tree.

    A selector naming a file the base does not have is a pytest USAGE error
    ("not found"), which aborts the whole base run before any test executes and
    would leave the lane with no baseline at all.
    """
    kept: list[str] = []
    for selector in selectors:
        relative = selector.split("::", 1)[0]
        if any(
            (root / relative).is_file()
            for root in (base_root, base_root / "backend")
        ):
            kept.append(selector)
    return kept


def _run_lane(repo: Path, base: str, *, fix: bool = False) -> int:
    changed = _changed_files(repo, base)
    sentinels = select_sentinels(changed, str(repo))
    if not sentinels:
        print(f"{PREFIX} no registered drift-sentinel surface changed; skipping")
        return 0

    print(f"{PREFIX} drift sentinels registered for this diff:")
    for sentinel in sentinels:
        print(f"  - {sentinel}")
    selectors = [_harness_selector(sentinel) for sentinel in sentinels]

    base_ref = _base_ref(repo, base)
    if base_ref is None:
        print(
            f"{PREFIX} ERROR: cannot resolve base ref origin/{base} or {base}; "
            "refusing to report clean without a baseline",
            file=sys.stderr,
        )
        return 2

    with tempfile.TemporaryDirectory(prefix="blueprint-sentinel-freshness-") as tmp:
        current_junit = Path(tmp) / "current.xml"
        current_result = _run_static_corpus(repo, current_junit, selectors=selectors)
        try:
            current_report = parse_junit_report(
                current_junit, tree_root=repo, label="current"
            )
        except RuntimeError as exc:
            print(f"{PREFIX} ERROR: cannot read the sentinel run: {exc}", file=sys.stderr)
            print(current_result.stdout, end="")
            print(current_result.stderr, end="", file=sys.stderr)
            return 1
        if not _pytest_result_is_authoritative(
            current_result, current_report, authority="sentinel_run_unusable"
        ):
            print(
                f"{PREFIX} ERROR: the sentinel run is not attributable; refusing "
                "to report clean",
                file=sys.stderr,
            )
            return 1
        if not current_report.failures:
            print(f"{PREFIX} PASS - every registered sentinel for this diff is fresh")
            return 0

        if fix:
            # Repair BEFORE attribution, deliberately. Attribution decides who
            # is to blame; repair decides whether anyone still has to be. A
            # sentinel healed here needs no baseline at all, so the fleet-level
            # case -- drift inherited from the base branch that today nobody
            # ever fixes -- is carried out on this PR instead of being warned
            # about again.
            healed = _self_repair(repo, tmp, sentinels, current_report)
            if healed is not None:
                return healed

        base_root = Path(tmp) / "base"
        base_root.mkdir()
        try:
            _extract_base(repo, base_ref, base_root)
        except RuntimeError as exc:
            print(f"{PREFIX} ERROR: cannot extract the base tree: {exc}", file=sys.stderr)
            return 1
        base_selectors = _base_selectors(selectors, base_root)
        if not base_selectors:
            baseline_report = JUnitReport()
        else:
            base_junit = Path(tmp) / "base.xml"
            base_result = _run_static_corpus(
                base_root, base_junit, selectors=base_selectors
            )
            try:
                baseline_report = parse_junit_report(
                    base_junit, tree_root=base_root, label="base"
                )
            except RuntimeError as exc:
                print(
                    f"{PREFIX} ERROR: cannot read the baseline sentinel run: {exc}",
                    file=sys.stderr,
                )
                return 1
            if not _pytest_result_is_authoritative(
                base_result, baseline_report, authority="sentinel_baseline_unusable"
            ):
                print(
                    f"{PREFIX} ERROR: the baseline sentinel run is not attributable; "
                    "refusing to charge or excuse this failure without it",
                    file=sys.stderr,
                )
                return 1

        outcome = classify_verification(
            runtime_available=True,
            current_exit_code=current_result.returncode,
            current_report=current_report,
            baseline_report=baseline_report,
        )
        new_failures = dict(outcome["new_failures"])
        inherited = {
            key: value
            for key, value in current_report.failures.items()
            if key not in new_failures
        }

        if inherited:
            stale = _failing_sentinels(inherited, sentinels)
            print(
                f"{PREFIX} BASE GUARD DATA STALE on {base_ref} - "
                f"{json.dumps(sorted(inherited))}. This does NOT block your "
                "change (the drift is inherited), but it WILL fail-close the "
                "next promotion PR until it is refreshed on the base branch.",
                file=sys.stderr,
            )
            _report_sentinels("stale on base", stale, sys.stderr)

        if new_failures:
            drifted = _failing_sentinels(new_failures, sentinels)
            print(
                f"{PREFIX} FAIL - this change leaves derived guard data stale: "
                f"{json.dumps(sorted(new_failures))}",
                file=sys.stderr,
            )
            _report_sentinels("drifted", drifted, sys.stderr)
            print(current_result.stdout, end="")
            print(current_result.stderr, end="", file=sys.stderr)
            return 1

    print(f"{PREFIX} PASS - no NEW derived-artifact drift attributable to this change")
    return 0


def main(argv: list[str] | None = None) -> int:
    force_utf8_streams()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default="automain")
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    parser.add_argument(
        "--fix",
        action="store_true",
        help=(
            "regenerate a drifted artifact that is registered as decision-free "
            "in derived_artifact_repair.AUTOREPAIRABLE, then re-run its sentinel "
            "to confirm the drift cleared. Ratchets, floors, snapshots, caps and "
            "measured durations are never regenerated, with or without this flag."
        ),
    )
    args = parser.parse_args(argv)
    try:
        return _run_lane(args.repo_root.resolve(), args.base, fix=args.fix)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"{PREFIX} ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
