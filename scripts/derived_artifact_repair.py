#!/usr/bin/env python3
"""Regenerate the derived artifacts that carry no human decision.

WHY A REPAIR PASS EXISTS AT ALL
-------------------------------
``scripts/sentinel_freshness.py`` already DETECTS every registered derived
artifact that has gone stale, attributes it to the diff that caused it, and
prints the exact regeneration command.  Detection was never the gap.  The gap
is that nothing ever RUNS that command: a stale artifact is repaired only when
a human notices the message, and the record shows what that costs --
``e38d74d4e1`` ("Green the derived-artifact guards before the promotion PR"),
``084cda2dd7`` ("Refresh the stale test-estate ranked queue on automain") and
``7e8069cde0`` ("Regenerate test-estate-ranked-queue.md for the promotion
bundle") are three hand-written repair commits in three days, each one cut
after a promotion PR had already gone red.

The class is also self-concealing by design: the freshness lane warn-passes
INHERITED drift, because drift someone else introduced must never stop the
fleet.  That is the right call for blocking and the wrong call for repair --
it means drift that reaches the integration branch is repaired by nobody until
the promotion matrix fail-closes on it.

This module closes that loop.  When the lane sees a drifted sentinel whose
artifact is listed here, it re-runs the artifact's own generator instead of
merely naming it.  ``./pr open`` stages the working tree with ``git add -A``
(agent/src/prompts/pr-helper.ts), so the regenerated bytes ride out on the same
PR, and the drift never reaches the integration branch in the first place.
Inherited drift is healed the same way: the next PR to touch the surface
carries the repair forward for everyone.

WHY THE ALLOWLIST IS SHORT, AND MUST STAY SHORT
-----------------------------------------------
"A guard that regenerates its own evidence is not a guard" is true of MOST of
this repository's derived artifacts, and this module must not be read as
retiring that rule.  The distinction that decides it is whether the artifact
encodes a DECISION:

* A **ratchet, floor, snapshot or cap** encodes a decision.  The emitter
  inventory fixture says "these are the emitters we have reviewed"; the
  conversational-Workday manifest's ``test_count`` entries are protection
  FLOORS; ``event_type_snapshot.json`` is the pinned literal set; the size
  ledger is policy.  Regenerating any of those silently ratifies a change a
  human was supposed to approve -- that is not a repair, it is deleting the
  guard.  They are listed in :data:`NEVER_AUTOREPAIR` with the reason, and the
  guard test pins each one by name.

* A **measurement** encodes an observation nothing in the tree can reproduce.
  ``backend/.test_durations`` and the two ``.test_durations.json`` files come
  from timed runs; "regenerating" them from a checkout would fabricate data.

* A **pure report** encodes neither.  ``test-estate-ranked-queue.md`` is a
  total function of the checked-out tree, it has no consumer other than the
  guard that compares it to that tree (nothing in ``backend/app``, the agent,
  CI sharding or the runtime reads it), and the entire correct human response
  to "it is stale" is "run the generator".  There is no review signal to lose.

Only the third kind belongs here.

WHAT THIS MODULE DOES NOT DO
----------------------------
It does not weaken, skip or reinterpret any assertion.  The guards keep
comparing the checked-in bytes against the tree exactly as before, and the
lane re-runs the sentinel AFTER a repair rather than assuming it worked -- a
repair that does not clear the drift still blocks.
"""

from __future__ import annotations

import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

__all__ = [
    "AutoRepair",
    "RepairOutcome",
    "AUTOREPAIRABLE",
    "ROT_ONLY_AUTOREPAIR",
    "NEVER_AUTOREPAIR",
    "MEASUREMENT_TAX_GUIDANCE",
    "repair_entry",
    "repair_sentinels",
]


@dataclass(frozen=True)
class AutoRepair:
    """A generator that may be run unattended to refresh ``artifacts``."""

    script: str
    """Repo-relative path to the generator, run with the current interpreter."""

    args: tuple[str, ...]
    """Arguments that put the generator in write mode."""

    artifacts: tuple[str, ...]
    """Repo-relative files the generator rewrites, used to report what moved."""

    why: str
    """Why this artifact is decision-free, i.e. why running it is safe."""


AUTOREPAIRABLE: dict[str, AutoRepair] = {
    "backend/testing/test_test_estate_ranked_queue.py": AutoRepair(
        script="scripts/generate_test_estate_ranked_queue.py",
        args=("--write",),
        artifacts=("test-estate-ranked-queue.md",),
        why=(
            "The ranked queue is a pure report: render_queue() is a total "
            "function of the checked-out tree, and no consumer reads it -- not "
            "backend/app, not the agent, not CI sharding, not the runtime. Its "
            "only reader is the sentinel that compares it to the tree it was "
            "derived from, so regenerating it discards no review signal. It is "
            "also the highest-frequency promotion blocker in the repo: adding "
            "any backend/testing/test_*.py or vitest test file stales it."
        ),
    ),
}


