@dataclass(frozen=True)
class RepairOutcome:
    """What a repair pass did, in enough detail to report and to fail closed."""

    repaired: tuple[str, ...] = ()
    """Sentinels whose artifact bytes actually changed."""

    already_fresh: tuple[str, ...] = ()
    """Sentinels whose generator ran and produced identical bytes."""

    skipped: tuple[str, ...] = ()
    """Drifted sentinels with no registered auto-repair (a ratchet, a floor…)."""

    failed: dict[str, str] = field(default_factory=dict)
    """Sentinel -> why its generator could not be run to completion."""

    @property
    def ran(self) -> tuple[str, ...]:
        return tuple(sorted({*self.repaired, *self.already_fresh}))

    def changed_artifacts(self) -> tuple[str, ...]:
        return tuple(
            sorted(
                {
                    artifact
                    for sentinel in self.repaired
                    for artifact in repair_entry(sentinel).artifacts
                }
            )
        )

    def merge(self, other: "RepairOutcome") -> "RepairOutcome":
        """Combine two passes over disjoint registries into one report."""
        return RepairOutcome(
            repaired=tuple(sorted({*self.repaired, *other.repaired})),
            already_fresh=tuple(sorted({*self.already_fresh, *other.already_fresh})),
            skipped=tuple(sorted({*self.skipped, *other.skipped})),
            failed={**self.failed, **other.failed},
        )


def repair_entry(sentinel: str) -> AutoRepair:
    """The registered repair for ``sentinel``, from whichever registry owns it.

    The two registries are disjoint by construction and that is pinned by
    ``test_derived_artifact_repair.py``, so this lookup is unambiguous.
    """
    entry = AUTOREPAIRABLE.get(sentinel) or ROT_ONLY_AUTOREPAIR.get(sentinel)
    if entry is None:  # pragma: no cover - callers only pass repaired sentinels
        raise KeyError(sentinel)
    return entry


def _snapshot(repo: Path, artifacts: Iterable[str]) -> dict[str, bytes | None]:
    """Read each artifact's current bytes, or ``None`` when it is absent."""
    state: dict[str, bytes | None] = {}
    for artifact in artifacts:
        path = repo / artifact
        try:
            state[artifact] = path.read_bytes()
        except OSError:
            state[artifact] = None
    return state


def repair_sentinels(
    repo: Path,
    sentinels: Iterable[str],
    registry: dict[str, AutoRepair] | None = None,
) -> RepairOutcome:
    """Run the registered generator for each auto-repairable ``sentinel``.

    Fail-closed by construction: a generator that is missing, that exits
    non-zero, or that leaves its declared artifact absent is recorded in
    ``failed`` rather than being reported as a repair.  Sentinels that are not
    in ``registry`` (default :data:`AUTOREPAIRABLE`) are recorded in ``skipped``
    and NEVER run -- this function has no fallback path that would let an
    unlisted regeneration command execute, and passing an explicit registry
    NARROWS what may run rather than widening it.
    """
    if registry is None:
        registry = AUTOREPAIRABLE
    repaired: list[str] = []
    already_fresh: list[str] = []
    skipped: list[str] = []
    failed: dict[str, str] = {}

    for sentinel in sorted(set(sentinels)):
        entry = registry.get(sentinel)
        if entry is None:
            skipped.append(sentinel)
            continue
        script = repo / entry.script
        if not script.is_file():
            failed[sentinel] = f"generator not found: {entry.script}"
            continue
        before = _snapshot(repo, entry.artifacts)
        try:
            result = subprocess.run(
                [sys.executable, str(script), *entry.args],
                cwd=repo,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
            )
        except OSError as exc:  # pragma: no cover - interpreter/exec failure
            failed[sentinel] = f"could not run {entry.script}: {exc}"
            continue
        if result.returncode != 0:
            failed[sentinel] = (
                f"{entry.script} {' '.join(entry.args)} exited "
                f"{result.returncode}: {(result.stderr or result.stdout).strip()[:400]}"
            )
            continue
        after = _snapshot(repo, entry.artifacts)
        missing = [name for name, data in after.items() if data is None]
        if missing:
            failed[sentinel] = (
                f"{entry.script} exited 0 but left {missing} absent; refusing to "
                "report a repair that produced no artifact"
            )
            continue
        if after != before:
            repaired.append(sentinel)
        else:
            already_fresh.append(sentinel)

    return RepairOutcome(
        repaired=tuple(repaired),
        already_fresh=tuple(already_fresh),
        skipped=tuple(skipped),
        failed=failed,
    )
